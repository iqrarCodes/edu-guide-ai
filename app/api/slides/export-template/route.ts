import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server'
import PptxGenJS from 'pptxgenjs'
import { SLIDE_TEMPLATES, TemplateId } from '@/lib/slide-templates'

const clean = (text: string): string => {
    if (!text) return ''
    return String(text)
        .replace(/[\x00-\x1F\x7F]/g, '')
        .replace(/[\u{1F300}-\u{1F9FF}]/gu, '')
        .trim()
}

export async function POST(request: NextRequest) {
    const supabase = await createClient()
    const { data: { user } } = await supabase.auth.getUser()
    if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

    const body = await request.json()
    const { templateId, slides, title } = body
    if (!templateId || !slides || !title) return NextResponse.json({ error: 'Missing fields' }, { status: 400 })

    const template = SLIDE_TEMPLATES[templateId as TemplateId] || SLIDE_TEMPLATES.modern

    try {
        const buffer = await generatePPTX(slides, title, template)
        return new NextResponse(new Uint8Array(buffer), {
            headers: {
                'Content-Type': 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
                'Content-Disposition': `attachment; filename="${title.replace(/\s+/g, '_')}.pptx"`,
            },
        })
    } catch (error: any) {
        console.error('Export error:', error)
        return NextResponse.json({ error: error.message || 'Failed' }, { status: 500 })
    }
}

async function generatePPTX(slides: any[], title: string, template: any): Promise<Buffer> {
    const pptx = new PptxGenJS()
    pptx.defineLayout({ name: 'WIDE', width: 13.33, height: 7.5 })
    pptx.layout = 'WIDE'

    const layout = template.layout || 'left-bar'
    const colors = template.styles.colors
    const styles = template.styles

    renderTitleSlide(pptx, title, layout, colors, styles)

    for (let idx = 0; idx < slides.length; idx++) {
        const slide = slides[idx]
        const s = pptx.addSlide()

        switch (layout) {
            case 'left-bar':    renderLeftBar(s, slide, idx, slides.length, colors, styles); break
            case 'top-banner':  renderTopBanner(s, slide, idx, slides.length, colors, styles); break
            case 'big-circles': renderBigCircles(s, slide, idx, slides.length, colors, styles); break
            case 'sidebar':     renderSidebar(s, slide, idx, slides.length, colors, styles); break
            case 'hero-center': renderHeroCenter(s, slide, idx, slides.length, colors, styles); break
            case 'blocks':      renderBlocks(s, slide, idx, slides.length, colors, styles); break
            case 'numbered':    renderNumbered(s, slide, idx, slides.length, colors, styles); break
            case 'split':       renderSplit(s, slide, idx, slides.length, colors, styles); break
            case 'magazine':    renderMagazine(s, slide, idx, slides.length, colors, styles); break
            case 'timeline':    renderTimeline(s, slide, idx, slides.length, colors, styles); break
            case 'grid-2x2':    renderGrid2x2(s, slide, idx, slides.length, colors, styles); break
            case 'quote-focus': renderQuoteFocus(s, slide, idx, slides.length, colors, styles); break
            default:            renderLeftBar(s, slide, idx, slides.length, colors, styles)
        }
    }

    const endSlide = pptx.addSlide()
    endSlide.addShape(pptx.ShapeType.rect, { x: 0, y: 0, w: 13.33, h: 7.5, fill: { color: colors.accent }, line: { color: colors.accent } })
    endSlide.addText('Thank You', { x: 0.5, y: 2.5, w: 12.33, h: 1.5, fontSize: 54, color: 'FFFFFF', bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })
    endSlide.addText('Presented by EduGuide AI+', { x: 0.5, y: 4.5, w: 12.33, h: 0.8, fontSize: 20, color: 'FFFFFF', align: 'center', fontFace: 'Arial' })

    const buffer = await pptx.write({ outputType: 'nodebuffer' })
    return buffer as Buffer
}

// ============================================================
// TITLE SLIDE
// ============================================================
function renderTitleSlide(pptx: any, title: string, layout: string, colors: any, styles: any) {
    const ts = pptx.addSlide()
    ts.background = { color: colors.bg }
    const decoration = styles.titleSlide.decoration

    if (decoration === 'bar') {
        ts.addShape(pptx.ShapeType.rect, { x: 0, y: 0, w: 13.33, h: 2.8, fill: { color: colors.accent }, line: { color: colors.accent } })
        ts.addText(clean(title), { x: 0.5, y: 0.6, w: 12, h: 1.7, fontSize: 44, color: 'FFFFFF', bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })
        ts.addText('Generated by EduGuide AI+', { x: 0.5, y: 3.6, w: 12.33, h: 0.9, fontSize: 20, color: colors.text, align: 'center', fontFace: 'Arial' })
        ts.addShape(pptx.ShapeType.rect, { x: 5, y: 5.5, w: 3.33, h: 0.08, fill: { color: colors.accent }, line: { color: colors.accent } })
    } else if (decoration === 'circle') {
        ts.addShape(pptx.ShapeType.ellipse, { x: -1.5, y: -1.5, w: 6, h: 6, fill: { color: colors.secondary }, line: { color: colors.secondary } })
        ts.addShape(pptx.ShapeType.ellipse, { x: 9.5, y: 3.5, w: 5, h: 5, fill: { color: colors.secondary }, line: { color: colors.secondary } })
        ts.addText(clean(title), { x: 0.5, y: 2.5, w: 12.33, h: 2, fontSize: 48, color: colors.text, bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })
        ts.addText('Generated by EduGuide AI+', { x: 0.5, y: 4.8, w: 12.33, h: 0.8, fontSize: 20, color: colors.text, align: 'center', fontFace: 'Arial' })
    } else if (decoration === 'block') {
        ts.addShape(pptx.ShapeType.rect, { x: 1.5, y: 1.5, w: 10.33, h: 4.5, fill: { color: colors.accent }, line: { color: colors.accent } })
        ts.addText(clean(title), { x: 1.8, y: 2, w: 9.73, h: 2.5, fontSize: 46, color: 'FFFFFF', bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })
        ts.addText('Generated by EduGuide AI+', { x: 0.5, y: 6.3, w: 12.33, h: 0.8, fontSize: 18, color: colors.text, align: 'center', fontFace: 'Arial' })
    } else {
        ts.addText(clean(title), { x: 1, y: 2, w: 11.33, h: 2, fontSize: 44, color: colors.text, bold: true, align: 'left', valign: 'middle', fontFace: 'Arial' })
        ts.addText('Generated by EduGuide AI+', { x: 1, y: 4.2, w: 11.33, h: 0.8, fontSize: 18, color: colors.primary, align: 'left', fontFace: 'Arial' })
        ts.addShape(pptx.ShapeType.rect, { x: 1, y: 5.2, w: 3, h: 0.06, fill: { color: colors.accent }, line: { color: colors.accent } })
    }
}

