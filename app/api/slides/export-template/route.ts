// LAYOUT 5: QUOTE SLIDE
// ============================================================
function renderQuoteSlide(s: any, slide: any, colors: any, x: number) {
    s.addText('"', {
        x: x - 0.2, y: 1.8, w: 2, h: 2,
        fontSize: 120, color: colors.accent, bold: true,
        align: 'left', valign: 'top', fontFace: 'Arial',
    })

    s.addText(clean(slide.quote || ''), {
        x: x + 1, y: 2.8, w: 10.5, h: 2.5,
        fontSize: 24, color: colors.text, italic: true,
        align: 'center', valign: 'middle', fontFace: 'Arial',
    })

    if (slide.author) {
        s.addShape('rect', {
            x: x + 4.5, y: 5.6, w: 3, h: 0.05,
            fill: { color: colors.accent }, line: { color: colors.accent },
        })
        s.addText(`— ${clean(slide.author)}`, {
            x: x, y: 5.8, w: 11.8, h: 0.6,
            fontSize: 16, color: colors.accent, bold: true,
            align: 'center', valign: 'middle', fontFace: 'Arial',
        })
    }
}

// ============================================================
// LAYOUT 6: ICON GRID
// ============================================================
function renderIconGridSlide(s: any, slide: any, colors: any, x: number) {
    const items = (slide.items || []).slice(0, 6)
    if (items.length === 0) return

    const cols = 3
    const cellW = 3.7
    const cellH = 1.9
    const gapX = 0.35
    const gapY = 0.3
    const startY = 2.3

    items.forEach((item: any, i: number) => {
        const row = Math.floor(i / cols)
        const col = i % cols
        const cellX = x + col * (cellW + gapX)
        const cellY = startY + row * (cellH + gapY)

        s.addShape('rect', {
            x: cellX, y: cellY, w: cellW, h: cellH,
            fill: { color: colors.cardBg || 'FFFFFF' },
            line: { color: colors.accent, width: 1 },
        })

        s.addShape('ellipse', {
            x: cellX + 0.2, y: cellY + 0.45, w: 0.9, h: 0.9,
            fill: { color: colors.accent }, line: { color: colors.accent },
        })
        s.addText(clean(item.icon || '●'), {
            x: cellX + 0.2, y: cellY + 0.45, w: 0.9, h: 0.9,
            fontSize: 24, color: 'FFFFFF', bold: true,
            align: 'center', valign: 'middle', fontFace: 'Arial',
        })

        s.addText(clean(item.label || ''), {
            x: cellX + 1.25, y: cellY, w: cellW - 1.4, h: cellH,
            fontSize: 14, color: colors.text, bold: true,
            align: 'left', valign: 'middle', fontFace: 'Arial',
        })
    })
}

// ============================================================
// LAYOUT 7: CONTENT (default)
// ============================================================
function renderContentSlide(s: any, slide: any, colors: any, styles: any, x: number) {
    const bullets = (slide.bullets || ['No content']).slice(0, 8)
    const bulletStyle = styles.contentSlide.bulletStyle
    let prefixChar = '• '
    if (bulletStyle === 'arrow') prefixChar = '▸ '
    else if (bulletStyle === 'check') prefixChar = '✓ '

    let yPos = 2.2
    bullets.forEach((bullet: string, i: number) => {
        const prefix = bulletStyle === 'number' ? `${i + 1}. ` : prefixChar

        if (bulletStyle === 'arrow' || bulletStyle === 'check') {
            s.addText(prefix.trim(), {
                x: x, y: yPos, w: 0.4, h: 0.6,
                fontSize: 18, color: colors.accent, bold: true,
                valign: 'middle', fontFace: 'Arial',
            })
            s.addText(clean(bullet), {
                x: x + 0.4, y: yPos, w: 11.3, h: 0.6,
                fontSize: 16, color: colors.text,
                valign: 'middle', fontFace: 'Arial',
            })
        } else {
            s.addText(`${prefix}${clean(bullet)}`, {
                x: x, y: yPos, w: 11.7, h: 0.6,
                fontSize: 16, color: colors.text,
                valign: 'middle', fontFace: 'Arial',
            })
        }
        yPos += 0.75
    })
}