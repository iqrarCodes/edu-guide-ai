// CONTENT: Stats
// ============================================================
function renderStats(s: any, slide: any, colors: any, x: number, y: number, w: number) {
    const stats = (slide.stats || []).slice(0, 4)
    if (!stats.length) return
    const gap = 0.3
    const cw = (w - gap * (stats.length - 1)) / stats.length
    const cardH = Math.min(2.8, 5.85 - y)

    stats.forEach((st: any, i: number) => {
        const cx = x + i * (cw + gap)
        s.addShape('rect', { x: cx, y, w: cw, h: cardH, fill: { color: colors.cardBg }, line: { color: colors.accent, width: 1.5 } })
        s.addShape('rect', { x: cx, y, w: cw, h: 0.15, fill: { color: colors.accent }, line: { color: colors.accent } })
        s.addText(clean(st.value || '0'), { x: cx, y: y + 0.4, w: cw, h: 1.3, fontSize: 42, color: colors.accent, bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })
        s.addText(clean(st.label || ''), { x: cx + 0.15, y: y + 1.75, w: cw - 0.3, h: 0.8, fontSize: 11, color: colors.text, align: 'center', valign: 'middle', fontFace: 'Arial' })
    })
}

// ============================================================
// CONTENT: PROCESS - VERTICAL (Fixed!)
// ============================================================
function renderProcessVertical(s: any, slide: any, colors: any, x: number, y: number, w: number) {
    const steps = (slide.steps || []).slice(0, 4)
    if (!steps.length) return

    const startY = y
    const stepH = Math.min(1.05, (5.85 - y) / steps.length)
    const circleSize = 0.55
    const textX = x + circleSize + 0.4

    // Vertical connecting line
    if (steps.length > 1) {
        s.addShape('rect', {
            x: x + (circleSize / 2) - 0.02,
            y: startY + circleSize,
            w: 0.04,
            h: (stepH * (steps.length - 1)),
            fill: { color: colors.accent },
            line: { color: colors.accent },
        })
    }

    steps.forEach((step: string, i: number) => {
        const stepY = startY + i * stepH

        // Numbered circle
        s.addShape('ellipse', {
            x, y: stepY,
            w: circleSize, h: circleSize,
            fill: { color: colors.accent },
            line: { color: colors.accent },
        })
        s.addText(String(i + 1), {
            x, y: stepY,
            w: circleSize, h: circleSize,
            fontSize: 18, color: 'FFFFFF', bold: true,
            align: 'center', valign: 'middle', fontFace: 'Arial',
        })

        // Step text (to the right of circle)
        s.addText(clean(step), {
            x: textX, y: stepY - 0.05,
            w: w - (circleSize + 0.4), h: stepH + 0.1,
            fontSize: 14, color: colors.text,
            valign: 'middle', fontFace: 'Arial',
            align: 'left',
        })
    })
}

// ============================================================
// CONTENT: Comparison
// ============================================================
function renderComparison(s: any, slide: any, colors: any, x: number, y: number, w: number) {
    const halfW = (w - 0.4) / 2
    const cardH = Math.min(3.7, 5.85 - y)

    ;['left', 'right'].forEach((side: string, si: number) => {
        const cx = x + si * (halfW + 0.4)
        const title = si === 0 ? slide.leftTitle : slide.rightTitle
        const items = ((si === 0 ? slide.leftItems : slide.rightItems) || []).slice(0, 4)
        const col = si === 0 ? colors.accent : colors.secondary

        s.addShape('rect', { x: cx, y, w: halfW, h: cardH, fill: { color: colors.cardBg }, line: { color: col, width: 1.5 } })
        s.addShape('rect', { x: cx, y, w: halfW, h: 0.6, fill: { color: col }, line: { color: col } })
        s.addText(clean(title || ''), { x: cx, y, w: halfW, h: 0.6, fontSize: 14, color: 'FFFFFF', bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })

        const itemH = (cardH - 0.7) / Math.max(items.length, 1)
        items.forEach((it: string, i: number) => {
            s.addText(`• ${clean(it)}`, {
                x: cx + 0.15, y: y + 0.7 + i * itemH,
                w: halfW - 0.3, h: itemH,
                fontSize: 10, color: colors.text,
                valign: 'middle', fontFace: 'Arial',
            })
        })
    })
}

