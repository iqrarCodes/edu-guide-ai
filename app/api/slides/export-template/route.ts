// ============================================================
// CONTENT: Icon Grid
// ============================================================
function renderIconGrid(s: any, slide: any, colors: any, x: number, y: number, w: number) {
    const items = (slide.items || []).slice(0, 6)
    if (!items.length) return

    const cols = 3
    const gap = 0.25
    const cw = (w - gap * (cols - 1)) / cols
    const availH = 5.85 - y
    const ch = (availH - gap) / 2

    items.forEach((it: any, i: number) => {
        const row = Math.floor(i / cols)
        const col = i % cols
        const cx = x + col * (cw + gap)
        const cy = y + row * (ch + gap)

        s.addShape('rect', { x: cx, y: cy, w: cw, h: ch, fill: { color: colors.cardBg }, line: { color: colors.accent, width: 1 } })
        s.addShape('ellipse', { x: cx + 0.15, y: cy + (ch / 2) - 0.35, w: 0.7, h: 0.7, fill: { color: colors.accent }, line: { color: colors.accent } })
        s.addText(clean(it.icon || '●'), { x: cx + 0.15, y: cy + (ch / 2) - 0.35, w: 0.7, h: 0.7, fontSize: 18, color: 'FFFFFF', bold: true, align: 'center', valign: 'middle', fontFace: 'Arial' })
        s.addText(clean(it.label || ''), { x: cx + 0.95, y: cy, w: cw - 1.1, h: ch, fontSize: 11, color: colors.text, bold: true, valign: 'middle', fontFace: 'Arial' })
    })
}

