function renderChart(s: any, slide: any, colors: any, x: number, y: number, w: number) {
    const data = (slide.chartData || []).slice(0, 6)
    if (!data.length) return
    let type = 'bar'
    if (slide.chartType === 'pie') type = 'pie'
    else if (slide.chartType === 'line') type = 'line'
    else if (slide.chartType === 'doughnut') type = 'doughnut'

    const h = Math.min(3.7, 5.85 - y)

    s.addChart(type, [{
        name: clean(slide.title || 'Data'),
        labels: data.map((d: any) => clean(d.label)),
        values: data.map((d: any) => Number(d.value) || 0),
    }], {
        x, y, w, h,
        showLegend: true, legendPos: 'b', showValue: true,
        chartColors: [colors.accent, colors.secondary, colors.primary, '6366F1', 'EC4899', 'F97316'],
    })
}

