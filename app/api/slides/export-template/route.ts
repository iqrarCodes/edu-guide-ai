// LAYOUT 4: COMPARISON
// ============================================================
function renderComparisonSlide(s: any, slide: any, colors: any, x: number) {
    const halfW = 5.6
    const gap = 0.6

    s.addShape('rect', {
        x: x, y: 2.2, w: halfW, h: 4.1,
        fill: { color: colors.cardBg || 'FFFFFF' },
        line: { color: colors.accent, width: 1.5 },
    })
    s.addShape('rect', {
        x: x, y: 2.2, w: halfW, h: 0.7,
        fill: { color: colors.accent }, line: { color: colors.accent },
    })
    s.addText(clean(slide.leftTitle || 'Option A'), {
        x: x, y: 2.2, w: halfW, h: 0.7,
        fontSize: 20, color: 'FFFFFF', bold: true,
        align: 'center', valign: 'middle', fontFace: 'Arial',
    })

        ; (slide.leftItems || []).slice(0, 6).forEach((item: string, i: number) => {
            s.addText(`• ${clean(item)}`, {
                x: x + 0.3, y: 3.1 + i * 0.55, w: halfW - 0.6, h: 0.5,
                fontSize: 13, color: colors.text,
                valign: 'middle', fontFace: 'Arial',
            })
        })

    const rightX = x + halfW + gap
    s.addShape('rect', {
        x: rightX, y: 2.2, w: halfW, h: 4.1,
        fill: { color: colors.cardBg || 'FFFFFF' },
        line: { color: colors.secondary, width: 1.5 },
    })
    s.addShape('rect', {
        x: rightX, y: 2.2, w: halfW, h: 0.7,
        fill: { color: colors.secondary }, line: { color: colors.secondary },
    })
    s.addText(clean(slide.rightTitle || 'Option B'), {
        x: rightX, y: 2.2, w: halfW, h: 0.7,
        fontSize: 20, color: 'FFFFFF', bold: true,
        align: 'center', valign: 'middle', fontFace: 'Arial',
    })

        ; (slide.rightItems || []).slice(0, 6).forEach((item: string, i: number) => {
            s.addText(`• ${clean(item)}`, {
                x: rightX + 0.3, y: 3.1 + i * 0.55, w: halfW - 0.6, h: 0.5,
                fontSize: 13, color: colors.text,
                valign: 'middle', fontFace: 'Arial',
            })
        })

    const vsX = x + halfW + gap / 2 - 0.4
    s.addShape('ellipse', {
        x: vsX, y: 3.9, w: 0.8, h: 0.8,
        fill: { color: colors.primary }, line: { color: colors.primary },
    })
    s.addText('VS', {
        x: vsX, y: 3.9, w: 0.8, h: 0.8,
        fontSize: 14, color: 'FFFFFF', bold: true,
        align: 'center', valign: 'middle', fontFace: 'Arial',
    })
}

